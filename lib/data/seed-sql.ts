// Turns the seed files into supabase/seed.sql: idempotent upserts keyed on
// natural keys (state code, election slug, race slug, candidate slug), so it
// can be re-run after any edit to data/. Free of "@/" imports for plain Node.

import type {
  CandidateSeed,
  ElectionFile,
  RaceSeed,
  StatesFile,
} from "./seed-schema.ts";

const lit = (value: string | number | boolean | null): string => {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
};

const textArray = (values: string[]): string =>
  `array[${values.map(lit).join(", ")}]::text[]`;

export function raceLabel(race: Pick<RaceSeed, "office" | "district">): string {
  return race.district === null
    ? race.office
    : `${race.office}, District ${race.district}`;
}

export function searchTerms(
  candidate: Pick<CandidateSeed, "name">,
  race: Pick<RaceSeed, "office" | "district">,
): string[] {
  return [`"${candidate.name}" ${raceLabel(race)}`];
}

export function buildSeedSql(
  states: StatesFile,
  elections: ElectionFile[],
): string {
  const out: string[] = [
    "-- Generated by scripts/build-seed-sql.ts from data/*.json. Do not edit by hand;",
    "-- edit the JSON and run `npm run seed:sql`.",
    "",
    "insert into public.states (code, name, enabled) values",
    states.states
      .map((s) => `  (${lit(s.code)}, ${lit(s.name)}, ${lit(s.enabled)})`)
      .join(",\n"),
    "on conflict (code) do update set name = excluded.name, enabled = excluded.enabled;",
  ];

  for (const file of elections) {
    const e = file.election;
    const where = `e.state_code = ${lit(e.state_code)} and e.slug = ${lit(e.slug)}`;
    out.push(
      "",
      `-- ${e.state_code} ${e.name}, ${e.date}`,
      "insert into public.elections (state_code, slug, name, election_date, type) values",
      `  (${lit(e.state_code)}, ${lit(e.slug)}, ${lit(e.name)}, ${lit(e.date)}, ${lit(e.type)})`,
      "on conflict (state_code, slug) do update set name = excluded.name,",
      "  election_date = excluded.election_date, type = excluded.type;",
      "",
      "insert into public.races (election_id, slug, office, district, level, partisan, sort_order)",
      "select e.id, v.slug, v.office, v.district, v.level, v.partisan, v.sort_order",
      "from public.elections e cross join (values",
      file.races
        .map(
          (r, i) =>
            `  (${lit(r.slug)}, ${lit(r.office)}, ${lit(r.district)}::integer, ${lit(r.level)}, ${lit(r.partisan)}, ${i + 1})`,
        )
        .join(",\n"),
      ") as v (slug, office, district, level, partisan, sort_order)",
      `where ${where}`,
      "on conflict (election_id, slug) do update set office = excluded.office,",
      "  district = excluded.district, level = excluded.level,",
      "  partisan = excluded.partisan, sort_order = excluded.sort_order;",
    );

    const rows = file.races.flatMap((race) =>
      race.candidates.map(
        (c, i) =>
          `  (${lit(race.slug)}, ${lit(c.slug)}, ${lit(c.name)}, ${lit(c.party)}, ${lit(c.ballot_designation)}, ${lit(c.incumbent)}, ${textArray(searchTerms(c, race))}, ${i + 1})`,
      ),
    );
    if (rows.length === 0) {
      out.push(
        "",
        "-- No candidates yet: the certified list hasn't been copied in.",
      );
      continue;
    }
    out.push(
      "",
      "insert into public.candidates (race_id, slug, name, party, ballot_designation, incumbent, search_terms, sort_order)",
      "select r.id, v.slug, v.name, v.party, v.ballot_designation, v.incumbent, v.search_terms, v.sort_order",
      "from public.races r",
      "join public.elections e on e.id = r.election_id",
      "join (values",
      rows.join(",\n"),
      ") as v (race_slug, slug, name, party, ballot_designation, incumbent, search_terms, sort_order)",
      "  on v.race_slug = r.slug",
      `where ${where}`,
      "on conflict (race_id, slug) do update set name = excluded.name,",
      "  party = excluded.party, ballot_designation = excluded.ballot_designation,",
      "  incumbent = excluded.incumbent, search_terms = excluded.search_terms,",
      "  sort_order = excluded.sort_order;",
    );
  }
  return `${out.join("\n")}\n`;
}
